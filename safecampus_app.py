def severity_score(text: str, model_prob: float) -> float:
    s = str(text).lower()
    score = 0.5 * model_prob
    if any(w in s for w in TIER1_INSULT)       : score += 0.15
    if any(w in s for w in TIER2_THREAT)       : score += 0.25
    if any(w in s for w in TIER_RAGGING_MILD)  : score += 0.15
    if any(w in s for w in TIER_RAGGING_SEVERE): score += 0.35
    if any(p in s for p in TIER3_SELF_HARM)    : score += 0.50
    return round(min(score, 1.0), 4)

def get_flags(text: str) -> list:
    s, flags = str(text).lower(), []
    if any(w in s for w in TIER1_INSULT)       : flags.append("Insult / Harassment")
    if any(w in s for w in TIER2_THREAT)       : flags.append("Direct Threat")
    if any(w in s for w in TIER_RAGGING_MILD)  : flags.append("Academic / Hierarchy Abuse")
    if any(w in s for w in TIER_RAGGING_SEVERE): flags.append("Severe Ragging / Hazing")
    if any(p in s for p in TIER3_SELF_HARM)    : flags.append("Suicide / Self-harm Risk")
    return flags or ["None detected"]

# ── Model loader ──────────────────────────────────────────────────────────────
@st.cache_resource
def load_models():
    from transformers import pipeline

    LOCAL_PATH = os.path.join(os.path.dirname(__file__), "models", "distilbert_finetuned")
    FALLBACK   = "martin-ha/toxic-comment-model"

    # Try fine-tuned local model first
    if os.path.isdir(LOCAL_PATH):
        try:
            pipe = pipeline(
                "text-classification",
                model=LOCAL_PATH,
                tokenizer=LOCAL_PATH,
                device=-1,          # CPU; change to 0 for GPU
                truncation=True,
                max_length=128,
            )
            meta_path = os.path.join(LOCAL_PATH, "meta.json")
            meta = json.load(open(meta_path)) if os.path.exists(meta_path) else {}
            return pipe, "fine-tuned", meta
        except Exception as e:
            st.warning(f"Local model failed ({e}). Using fallback.")

    # Fallback: generic toxic model
    try:
        pipe = pipeline(
            "text-classification",
            model=FALLBACK,
            tokenizer=FALLBACK,
            device=-1,
            truncation=True,
            max_length=512,
        )
        return pipe, "fallback", {}
    except Exception as e:
        return None, "none", {}

# ── Prediction ────────────────────────────────────────────────────────────────
def predict_full(text, pipe, model_source):
    cleaned = clean_text(text)
    if pipe is None:
        return {"prediction":"Error","probability":0,"severity":0,
                "severity_raw":0,"flags":[],"cleaned_text":cleaned}

    res = pipe(cleaned, truncation=True)[0]

    # Fine-tuned model uses LABEL_0 / LABEL_1
    # Fallback uses toxic / non-toxic
    lbl = res["label"].lower()
    if "label_1" in lbl or "toxic" == lbl:
        prob = float(res["score"])
    elif "label_0" in lbl or "non-toxic" in lbl:
        prob = 1.0 - float(res["score"])
    else:
        prob = float(res["score"])

    sev   = severity_score(text, prob)
    flags = get_flags(text)

    return {
        "prediction"  : "Cyberbullying / Ragging" if prob > 0.5 else "Safe",
        "probability" : round(prob * 100, 1),
        "severity"    : round(sev  * 100, 1),
        "severity_raw": sev,
        "flags"       : flags,
        "cleaned_text": cleaned,
    }

# ── LIME explanation ──────────────────────────────────────────────────────────
def get_lime_words(text, pipe, n=15):
    try:
        from lime.lime_text import LimeTextExplainer

        def proba_fn(texts):
            results = pipe(
                [clean_text(t) for t in texts],
                truncation=True, batch_size=16
            )
            out = []
            for r in results:
                lbl = r["label"].lower()
                p   = float(r["score"])
                if "label_1" in lbl or lbl == "toxic":
                    out.append([1 - p, p])
                else:
                    out.append([p, 1 - p])
            return np.array(out)

        exp = LimeTextExplainer(class_names=["Safe", "Harmful"]).explain_instance(
            text, proba_fn, num_features=n, num_samples=80
        )
        return exp.as_list()
    except Exception as e:
        return []

