def _expand_contractions(text):
    try:    return contractions.fix(text)
    except: return text

def _correct_elongated(text):
    return re.sub(r"(\w)\1{2,}", r"\1", text)

def clean_text(s: str) -> str:
    """Light clean — keeps Hindi/Hinglish words intact for mDistilBERT."""
    s = emoji_lib.replace_emoji(str(s), replace=" ")
    s = _expand_contractions(s)
    s = re.sub(r"http\S+",  " ", s)
    s = re.sub(r"@\w+",     " ", s)
    s = re.sub(r"#",        " ", s)
    s = _correct_elongated(s)
    s = re.sub(r"\s+", " ", s).strip()
    return s[:512]

